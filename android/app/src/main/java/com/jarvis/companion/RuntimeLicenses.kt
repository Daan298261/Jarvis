    const val TITLE_PREFIX = "Gradle runtime libraries"

    /** One notice per license, listing every library under it, then the license link(s). */
    fun notices(): List<LicenseNotice> = libraries.groupBy { it.license }.map { (license, libs) ->
        LicenseNotice(
            title = "$TITLE_PREFIX: $license (${libs.size})",
            packId = "gradle-runtime-" + license.lowercase().replace(Regex("[^a-z0-9]+"), "-").trim('-'),
            attribution = "License: $license. " +
                libs.joinToString(", ") { "${it.coordinate} ${it.version}" } + ". " +
                licenseUrls.getValue(license),
        )
    }
